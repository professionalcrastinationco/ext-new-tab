// Generates brand-icons.js from the Simple Icons package (CC0 licensed).
// Run: node development/generate-brand-icons.js
const si = require('simple-icons');
const fs = require('fs');
const path = require('path');

const WANTED = [
  'google','youtube','gmail','googledrive','googlecalendar','googlemaps','googlephotos','googlegemini','googlecloud','googlechrome',
  'github','gitlab','cloudflare','vercel','netlify','docker','npm','stackoverflow','figma','notion','slack','discord','trello','asana',
  'linear','jira','atlassian','dropbox','zoom','spotify','netflix','twitch','reddit','x','facebook','instagram','whatsapp','telegram',
  'pinterest','tiktok','amazon','ebay','paypal','stripe','shopify','wikipedia','openai','anthropic','perplexity','huggingface',
  'firefoxbrowser','digitalocean','supabase','firebase','postman','python','react','tailwindcss','typescript','wordpress','medium',
  'substack','canva','airbnb','uber','evernote','todoist','bitwarden','1password','protonmail','duckduckgo','bluesky','mastodon',
  'threads','ycombinator','producthunt','apple','linkedin','microsoft','googledocs','googlesheets','googleanalytics','mailchimp',
  'hubspot','deepseek','salesforce','zapier','airtable','miro','loom','calendly','obsidian','steam','imdb','github'
];

const out = {};
const missing = [];
for (const slug of [...new Set(WANTED)]) {
  const key = 'si' + slug.charAt(0).toUpperCase() + slug.slice(1);
  const icon = si[key];
  if (!icon) { missing.push(slug); continue; }
  out[slug] = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" fill="currentColor" role="img"><title>${icon.title}</title><path d="${icon.path}"/></svg>`;
}

const body = `/**
 * Brand Icons (generated by development/generate-brand-icons.js)
 * Source: Simple Icons (https://simpleicons.org), CC0 1.0.
 * Brand names and logos are trademarks of their respective owners.
 */
const BRAND_ICONS = ${JSON.stringify(out, null, 1)};
`;
fs.writeFileSync(path.join(__dirname, '..', 'brand-icons.js'), body);
console.log('Wrote', Object.keys(out).length, 'icons. Missing:', missing.join(', ') || 'none');
